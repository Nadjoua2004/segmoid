"""Deploy the Aegis-Bio backend + AstroDoc AI to a Hugging Face Docker Space.

    python deploy/huggingface/deploy_space.py --space <hf-user>/aegis-bio-api

What it does:
  1. packs only what the server needs (aegis-bio/backend + astrodoc/backend, same folder layout),
     leaving out venvs, .env files, local databases, caches and tests
  2. creates the Space (Docker, public) if it does not exist
  3. stores the settings from deploy/huggingface/space.secrets.env as Space secrets / variables
     (that file is git-ignored; secrets never go into any repository)
  4. uploads the files; Hugging Face then builds the image and starts the server

Token: a Hugging Face token with WRITE access, from --token, the HF_DEPLOY_TOKEN environment variable,
HF_DEPLOY_TOKEN in space.secrets.env (never uploaded), or `hf auth login`.
"""
from __future__ import annotations

import argparse
import os
import secrets
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SECRETS_FILE = HERE / "space.secrets.env"

# Space settings: secrets are hidden after saving, variables stay visible in the Space settings.
SECRET_KEYS = ("LLM_API_KEY", "DATABASE_URL", "SECRET_KEY", "SUPABASE_KEY")
VARIABLE_KEYS = ("FRONTEND_ORIGINS", "FRONTEND_ORIGIN_REGEX", "SUPABASE_URL", "LLM_MODEL", "LLM_FALLBACK_MODELS")
REQUIRED = ("LLM_API_KEY", "DATABASE_URL", "FRONTEND_ORIGINS")

COMMON_IGNORE = ("venv", ".venv", "__pycache__", "*.pyc", ".pytest_cache", ".env", ".env.*", "*.sqlite3", "*.db",
                 "*.log", "tests", "node_modules")
SOURCES = {
    "aegis-bio/backend": COMMON_IGNORE + ("chroma_data",),
    "astrodoc/backend": COMMON_IGNORE + ("kb",),        # the knowledge index is rebuilt inside the image
}


def read_env_file(path: Path) -> dict[str, str]:
    values = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                values[k.strip()] = v.strip().strip('"').strip("'")
    return values


def ensure_secret_key(values: dict[str, str]) -> None:
    """Generate the JWT signing key once and keep it in the secrets file (a new key would log everyone out)."""
    if values.get("SECRET_KEY"):
        return
    values["SECRET_KEY"] = secrets.token_urlsafe(48)
    with SECRETS_FILE.open("a", encoding="utf-8") as f:
        f.write(f"\n# generated by deploy_space.py - keep it, a new key logs every user out\n"
                f"SECRET_KEY={values['SECRET_KEY']}\n")
    print("Generated SECRET_KEY and saved it in space.secrets.env")


def stage(dest: Path) -> None:
    for name in ("Dockerfile", "README.md", "requirements.txt"):
        shutil.copy2(HERE / name, dest / name)
    for rel, ignore in SOURCES.items():
        shutil.copytree(REPO / rel, dest / rel, ignore=shutil.ignore_patterns(*ignore))
    files = [p for p in dest.rglob("*") if p.is_file()]
    size = sum(p.stat().st_size for p in files) / 1024 / 1024
    print(f"Packed {len(files)} files ({size:.1f} MB)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--space", required=True, help="<hf-user>/<space-name>, e.g. tamer/aegis-bio-api")
    ap.add_argument("--token", default=os.getenv("HF_DEPLOY_TOKEN"), help="Hugging Face WRITE token")
    ap.add_argument("--dry-run", action="store_true", help="only pack the files and check the settings")
    args = ap.parse_args(argv)

    values = read_env_file(SECRETS_FILE)
    missing = [k for k in REQUIRED if not values.get(k)]
    if missing:
        print(f"Missing in {SECRETS_FILE.relative_to(REPO)}: {', '.join(missing)}\n"
              f"Copy space.secrets.example.env to space.secrets.env and fill it in.")
        return 1
    ensure_secret_key(values)

    with tempfile.TemporaryDirectory(prefix="aegis-space-") as tmp:
        stage(Path(tmp))
        if args.dry_run:
            print("Dry run: nothing uploaded.")
            return 0

        from huggingface_hub import HfApi
        api = HfApi(token=args.token or values.get("HF_DEPLOY_TOKEN") or None)
        user = api.whoami()["name"]
        print(f"Logged in to Hugging Face as {user}")
        api.create_repo(args.space, repo_type="space", space_sdk="docker", private=False, exist_ok=True)
        for key in SECRET_KEYS:
            if values.get(key):
                api.add_space_secret(args.space, key, values[key])
        for key in VARIABLE_KEYS:
            if values.get(key):
                api.add_space_variable(args.space, key, values[key])
        print("Space secrets and variables saved")
        api.upload_folder(repo_id=args.space, repo_type="space", folder_path=tmp,
                          commit_message="Deploy Aegis-Bio backend + AstroDoc AI", delete_patterns="*")

    owner, name = args.space.split("/", 1)
    url = f"https://{owner.lower()}-{name.lower().replace('_', '-').replace('.', '-')}.hf.space"
    print(f"\nUploaded. Hugging Face is now building the image (5-10 min the first time).\n"
          f"  Build logs: https://huggingface.co/spaces/{args.space}?logs=build\n"
          f"  API URL:    {url}   (use it as NEXT_PUBLIC_API_URL on Vercel)\n"
          f"  Check:      {url}/api/astrodoc/assistant/status")
    return 0


if __name__ == "__main__":
    sys.exit(main())
